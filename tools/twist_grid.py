"""twist_grid.py -- twist-averaged boundary conditions (TABC) for alea.

A finite periodic cell samples the Fermi sea only at the reciprocal-lattice
points k, which leaves a large single-particle "shell" error in the energy.
Twist averaging (Lin, Zong & Ceperley, PRE 64, 016702 (2001)) runs the same
system at a grid of twists theta = t1 b1 + t2 b2 and averages the energies;
the average samples k + theta densely and removes most of that error.  Each
twist is an independent alea run (a complex trial -> fixed-phase DMC), which
is how QMCPACK does it too (one run per twistnum, averaged afterwards).

Three steps, each resumable:

    py -3 tools/twist_grid.py make    BASE.yaml --grid 4 --out runs/tabc/heg
    py -3 tools/twist_grid.py run     runs/tabc/heg [--jobs 4 --threads 16]
    py -3 tools/twist_grid.py average runs/tabc/heg [--method dmc] [--driver -1]

make     writes one config per twist (BASE with lattice.twist and project.name
         set) plus twists.csv.  Twists form a Monkhorst-Pack-like grid,
         t_i = (m_i + offset)/n_i - 1/2.  By default t and -t are merged into
         one run of weight 2: for a real Hamiltonian (no magnetic field or
         rotation) psi_{-theta} = psi_theta^*, so both give the same energy.
run      runs alea on every config without an output yet, saving stdout to
         <config>.out.  A twist whose occupation is degenerate (alea refuses
         it) is reported and skipped; shift --offset to avoid it.
average  parses "<method>: E = x +/- e" from each .out (the --driver-th such
         line, default the last) and prints the weighted twist average
         E_TA = sum w E / sum w,  err = sqrt(sum w^2 e^2) / sum w,
         plus the spread across twists (the shell fluctuation being averaged).

Notes.  PyYAML rewrites the config, so BASE's comments are not carried into
the per-twist files.  On Windows alea is run with a PATH holding only the
MSYS2 ucrt64 runtime and the Windows system directories, so that no other
MinGW runtime DLLs are picked up.
"""

from __future__ import annotations

import argparse
import csv
import itertools
import math
import os
import re
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
WINDOWS = os.name == "nt"
ALEA = ROOT / "build" / ("alea.exe" if WINDOWS else "alea")
UCRT64 = r"C:\msys64\ucrt64\bin"

SUMMARY_RE = re.compile(r"^(vmc|dmc): E = (\S+) \+/- (\S+)", re.M)


# -- twist grid ---------------------------------------------------------------

def reduce_twist(t):
    """Fold each component into [-1/2, 1/2): t and t + integer are one twist."""
    return tuple(round(x - math.floor(x + 0.5), 12) + 0.0 for x in t)


def twist_grid(ns, offset, use_symmetry):
    """[(twist, weight)] on a Monkhorst-Pack-like grid, t -> -t merged if asked."""
    axes = [[(m + offset) / n - 0.5 for m in range(n)] for n in ns]
    pts = [reduce_twist(t) for t in itertools.product(*axes)]
    if not use_symmetry:
        return [(t, 1) for t in pts]
    out, seen = [], {}
    for t in pts:
        partner = reduce_twist([-x for x in t])
        if partner in seen:
            out[seen[partner]] = (out[seen[partner]][0], out[seen[partner]][1] + 1)
        else:
            seen[t] = len(out)
            out.append((t, 1))
    return out


# -- make ---------------------------------------------------------------------

def cmd_make(args):
    # PyYAML only here, so that twist_grid() can be imported (moire_cells.py
    # reports shells on this very grid) with the standard library alone.
    import yaml

    base = yaml.safe_load(Path(args.base).read_text(encoding="utf-8"))
    lat = base.get("system", {}).get("lattice", {})
    if lat.get("type") != "periodic":
        sys.exit("twist_grid: the base config must have a periodic lattice")
    dim = int(lat.get("dimension", 2))
    ns = args.grid if len(args.grid) == dim else args.grid * dim
    if len(ns) != dim:
        sys.exit(f"twist_grid: --grid needs 1 or {dim} values")

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    name = base.get("project", {}).get("name", Path(args.base).stem)
    rows = []
    for i, (t, w) in enumerate(twist_grid(ns, args.offset, not args.no_symmetry)):
        cfg = yaml.safe_load(yaml.safe_dump(base))       # deep copy
        cfg["system"]["lattice"]["twist"] = list(t)
        cfg.setdefault("project", {})["name"] = f"{name}_tw{i:03d}"
        path = out / f"twist_{i:03d}.yaml"
        path.write_text(
            f"# generated by tools/twist_grid.py from {args.base}\n"
            f"# twist t = {list(t)} (fractional reciprocal coordinates), weight {w}\n"
            + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")
        rows.append({"index": i, "twist": " ".join(f"{x:.12g}" for x in t),
                     "weight": w, "config": path.name})
    with (out / "twists.csv").open("w", newline="") as fh:
        wr = csv.DictWriter(fh, fieldnames=["index", "twist", "weight", "config"])
        wr.writeheader()
        wr.writerows(rows)
    total = sum(r["weight"] for r in rows)
    print(f"{len(rows)} runs covering {total} twists -> {out}")


def read_twists(d):
    with (Path(d) / "twists.csv").open(newline="") as fh:
        return list(csv.DictReader(fh))


# -- run ----------------------------------------------------------------------

def child_env(threads):
    env = dict(os.environ)
    if WINDOWS:
        sysroot = env.get("SystemRoot", r"C:\Windows")
        env["PATH"] = ";".join([UCRT64, os.path.join(sysroot, "System32"), sysroot])
    if threads > 0:
        env["OMP_NUM_THREADS"] = str(threads)
    return env


def cmd_run(args):
    d = Path(args.dir)
    todo = [r for r in read_twists(d)
            if not (d / (r["config"] + ".out")).exists()]
    print(f"{len(todo)} twist runs to do")

    def one(r):
        cfg = d / r["config"]
        proc = subprocess.run([str(args.alea), str(cfg)], capture_output=True,
                              text=True, encoding="utf-8", errors="replace",
                              env=child_env(args.threads))
        if proc.returncode != 0:
            return r, f"FAILED ({proc.returncode}): {proc.stderr.strip()[-300:]}"
        (d / (r["config"] + ".out")).write_text(proc.stdout, encoding="utf-8")
        last = SUMMARY_RE.findall(proc.stdout)
        return r, (f"{last[-1][0]} E = {last[-1][1]} +/- {last[-1][2]}"
                   if last else "done (no summary line)")

    with ThreadPoolExecutor(max_workers=max(1, args.jobs)) as ex:
        for r, msg in ex.map(one, todo):
            print(f"  twist {r['index']:>3} [{r['twist']}]  {msg}", flush=True)


# -- average ------------------------------------------------------------------

def cmd_average(args):
    d = Path(args.dir)
    got, missing = [], []
    for r in read_twists(d):
        out = d / (r["config"] + ".out")
        if not out.exists():
            missing.append(r["index"])
            continue
        hits = [(float(e), float(s)) for m, e, s in
                SUMMARY_RE.findall(out.read_text(encoding="utf-8"))
                if m == args.method]
        if not hits:
            missing.append(r["index"])
            continue
        e, s = hits[args.driver]
        got.append((r, int(r["weight"]), e, s))
    if not got:
        sys.exit(f"twist_grid: no '{args.method}' results in {d}")

    W = sum(w for _, w, _, _ in got)
    E = sum(w * e for _, w, e, _ in got) / W
    err = math.sqrt(sum((w * s) ** 2 for _, w, _, s in got)) / W
    spread = math.sqrt(sum(w * (e - E) ** 2 for _, w, e, _ in got) / W)
    for r, w, e, s in got:
        print(f"  twist {r['index']:>3} [{r['twist']}]  w={w}  E = {e:.8f} +/- {s:.8f}")
    print(f"{args.method} twist average over {W} twists ({len(got)} runs): "
          f"E = {E:.8f} +/- {err:.8f}   (spread across twists {spread:.6f})")
    if missing:
        print(f"WARNING: no {args.method} result for twist(s) {missing}; "
              "the average above omits them", file=sys.stderr)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)

    m = sub.add_parser("make", help="write one config per twist")
    m.add_argument("base")
    m.add_argument("--grid", type=int, nargs="+", required=True,
                   help="twists per reciprocal axis (one value = same on every axis)")
    m.add_argument("--offset", type=float, default=0.5,
                   help="grid offset in units of the spacing (0.5 = Monkhorst-Pack)")
    m.add_argument("--no-symmetry", action="store_true",
                   help="do not merge t and -t (needed with B field / rotation)")
    m.add_argument("--out", required=True)
    m.set_defaults(func=cmd_make)

    r = sub.add_parser("run", help="run alea on every twist without output yet")
    r.add_argument("dir")
    r.add_argument("--alea", type=Path, default=ALEA)
    r.add_argument("--jobs", type=int, default=1)
    r.add_argument("--threads", type=int, default=0,
                   help="OMP_NUM_THREADS per run (0 = leave unset)")
    r.set_defaults(func=cmd_run)

    a = sub.add_parser("average", help="weighted twist average of the energies")
    a.add_argument("dir")
    a.add_argument("--method", choices=["vmc", "dmc"], default="dmc")
    a.add_argument("--driver", type=int, default=-1,
                   help="which <method> summary line per run (default: the last)")
    a.set_defaults(func=cmd_average)

    args = ap.parse_args(argv)
    args.func(args)


if __name__ == "__main__":
    main()
