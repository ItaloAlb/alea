#pragma once

#include <cmath>

namespace alea::numerics {

// Bessel function of the first kind, order zero, J0(x), for x >= 0.
//
// Why this exists: libstdc++'s std::cyl_bessel_j costs ~1870 ns/call (measured;
// 267x a std::cos) and dominates the cost of the long-range breakup, whose
// c_n(k) and X(k) quadratures evaluate J0 ~1e8 times per setup.  It is *not* on
// any QMC hot path — the hot path never sees a Bessel function — but a setup
// that takes 5 minutes instead of 3 seconds is not acceptable either.
//
// Split point measured against a long-double evaluation of the same Hankel
// expansion, which separates our error from libstdc++'s:
//
//     x          asymptotic (4 terms)     std::cyl_bessel_j
//     20         1.2e-12                  4.6e-14
//     40         1.2e-14                  2.0e-15
//     60         2.8e-16                  2.6e-15
//     600        7.5e-16                  8.2e-14      <- std degrades
//
// So below x = 40 libstdc++ is the more accurate of the two, and above ~60 it
// is the *less* accurate one.  Splitting at 40 takes the better branch on both
// sides and caps our own error at 1.2e-14 — the breakup amplifies a J0 error
// into the energy by ~600x (measured), so this contributes ~7e-12, two orders
// below the breakup's own 2.7e-9.
inline constexpr double kJ0AsymptoticFrom = 40.0;

[[nodiscard]] inline double bessel_j0(double x) noexcept {
    if (x < kJ0AsymptoticFrom) {
        return std::cyl_bessel_j(0.0, x);
    }
    // Hankel's asymptotic expansion (Abramowitz & Stegun 9.2.5):
    //   J0(x) = sqrt(2/πx) [ P(x) cos(ω) − Q(x) sin(ω) ],   ω = x − π/4
    // with P ~ Σ (−1)^k a_{2k}/x^{2k} and Q ~ Σ (−1)^k a_{2k+1}/x^{2k+1},
    // the a_k generated by a_k = a_{k−1}(μ − (2k−1)²)/(8k) at μ = 4ν² = 0.
    const double z  = 1.0 / x;
    const double z2 = z * z;
    const double p = 1.0 + z2 * (-7.03125e-2 +
                     z2 * (1.121520996093750e-1 +
                     z2 * (-5.725014209747314e-1 +
                     z2 * 6.074042001273483e0)));
    const double q = z * (-1.25e-1 +
                    z2 * (7.32421875e-2 +
                    z2 * (-2.271080017089844e-1 +
                    z2 * 1.727727502584457e0)));
    const double w = x - 7.853981633974483096e-1;   // x − π/4
    // sqrt(2/π) = 0.7978845608…, so sqrt(2/(πx)) = sqrt(0.63661977…/x)
    return std::sqrt(6.366197723675814e-1 * z) *
           (p * std::cos(w) - q * std::sin(w));
}

}  // namespace alea::numerics
